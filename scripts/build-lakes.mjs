// Regenerates src/lakes.data.ts from the lakelevelnow.com site data so slugs, gauge bindings,
// full-pool references and seasonal target curves stay identical to the site.
// Usage: SITE_DIR=~/satellite-repos/lakelevelnow node scripts/build-lakes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SITE = process.env.SITE_DIR || join(process.env.HOME, 'satellite-repos/lakelevelnow');
const read = (f) => JSON.parse(readFileSync(join(SITE, 'src/data', f), 'utf8'));
const seed = read('lakes.seed.json');
const sources = read('sources.json');
const seasonal = read('seasonal-pools.json');
const almanac = read('almanac.json');
const almanacSlugs = new Set(almanac.lakes.map((l) => l.slug));

// TWDB reservoir names for USGS-bound Texas lakes (copied from scripts/fetch-levels.mjs TWDB_NAMES).
const TWDB_NAMES = {
  'lake-travis': 'travis', 'lake-buchanan': 'buchanan', 'medina-lake': 'medina', 'canyon-lake': 'canyon',
  'lake-belton': 'belton', 'lake-somerville': 'somerville', 'lake-fork': 'fork', 'lake-whitney': 'whitney',
};
// RISE item ids for the Lower Colorado reservoirs (copied from scripts/fetch-levels.mjs RISE_ITEMS).
const RISE_ITEMS = {
  'Lake Mead': { elev: 6123, sto: 6124 },
  'Lake Mohave': { elev: 6133, sto: 6134 },
  'Lake Havasu': { elev: 6128, sto: 6129 },
};

const lakes = seed.map((l) => {
  const s = sources[l.slug] || null;
  let feed = null;
  if (s) {
    if (s.feed === 'usgs') feed = { type: 'usgs', site: s.site, param: s.param };
    else if (s.feed === 'cdec') feed = { type: 'cdec', site: s.site };
    else if (s.feed === 'usbr') feed = { type: 'usbr', site: s.site, elevItem: RISE_ITEMS[s.site].elev, storageItem: RISE_ITEMS[s.site].sto };
    else if (s.feed === 'twdb') feed = { type: 'twdb', site: s.site };
    else if (s.feed === 'cwms') feed = { type: 'cwms', office: s.office, site: s.site };
  }
  const sp = seasonal[l.slug];
  const season = sp && sp.kind === 'curve'
    ? { name: sp.name, agency: sp.agency, interp: sp.interp, points: sp.points, source: sp.source?.url ?? null }
    : null;
  return {
    slug: l.slug, name: l.name, state: l.state, river: l.river ?? null, operator: l.operator ?? null,
    fullPoolFt: l.full_pool_ft ?? null, capacityAf: l.capacity_af ?? null,
    feed, twdbName: TWDB_NAMES[l.slug] ?? null, seasonal: season, almanac: almanacSlugs.has(l.slug),
  };
});

const out = `// GENERATED by scripts/build-lakes.mjs from the lakelevelnow.com site data. Do not edit by hand.
// Sources: src/data/lakes.seed.json, sources.json, seasonal-pools.json, almanac.json of lakelevelnow.com.
import type { Lake } from './types.js';

export const LAKES_DATA_AS_OF = '${new Date().toISOString().slice(0, 10)}';

export const LAKES: Lake[] = ${JSON.stringify(lakes, null, 2)};
`;
writeFileSync(new URL('../src/lakes.data.ts', import.meta.url), out);
console.log(`wrote ${lakes.length} lakes (${lakes.filter((l) => l.feed).length} with a live feed, ${lakes.filter((l) => l.almanac).length} in the almanac)`);
